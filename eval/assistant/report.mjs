// Turn the evaluation runs in docs/results/assistant/*.json into docs/results/phase5_assistant.md.
//   node eval/assistant/report.mjs
// Uses the newest snapshot that has runs; partial runs (--only) are ignored.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const DIR = path.join(ROOT, "docs/results/assistant");
const OUT = path.join(ROOT, "docs/results/phase5_assistant.md");
const CATS = ["lookup", "place", "site", "anomaly", "forecast", "method", "trap"];
const CAT_LABEL = {
  lookup: "Lookups", place: "Places", site: "Single overflow", anomaly: "Unexpected spills",
  forecast: "Forecasts", method: "Method", trap: "Trap questions",
};

const runs = fs.existsSync(DIR)
  ? fs.readdirSync(DIR).filter((f) => f.endsWith(".json") && !f.includes("_partial")).map((f) => JSON.parse(fs.readFileSync(path.join(DIR, f))))
  : [];
if (!runs.length) {
  console.error("No complete runs in docs/results/assistant/. Run: npm run eval:assistant");
  process.exit(1);
}
const snapshot = runs.map((r) => r.snapshot).sort().at(-1);
const use = runs.filter((r) => r.snapshot === snapshot)
  .sort((a, b) => (a.mode === b.mode ? a.model.localeCompare(b.model) : a.mode === "tools" ? -1 : 1));

const pct = (n, d) => (d ? `${Math.round((100 * n) / d)}%` : "–");
const frac = (rs, f) => `${rs.filter(f).length}/${rs.length} (${pct(rs.filter(f).length, rs.length)})`;
const name = (r) => `${r.model}, ${r.mode === "tools" ? "with tools" : "**no tools**"}`;
const grounded = (x) => !x.error && !x.unsupported_numbers.length;
const mean = (rs, f) => { const ok = rs.filter((x) => !x.error); return ok.length ? ok.reduce((s, x) => s + f(x), 0) / ok.length : 0; };
const n = use[0].results.length;

let md = `# Phase 5 results: the SpillWatch AI assistant (RQ3)

*Generated by \`node eval/assistant/report.mjs\` from ${use.length} run(s) on data snapshot \`${snapshot}\`. Re-run with \`npm run eval:assistant\` (see README).*

## Research question
**RQ3:** Can a large language model, restricted to tools over SpillWatch's data, answer the public's questions about sewage spills accurately and without inventing facts, and how does it behave on questions it should decline?

## Method
- **${n} questions in ${CATS.length} categories**, including 7 *trap* questions (legality, swimming safety, next week's risk, E. coli levels, an unknown company, a false premise, an off-topic request). Expected answers are computed from the frozen snapshot with the same tool code the assistant uses.
- **Correct:** the answer contains the expected figure or behaviour (automatic check per question, listed in \`eval/assistant/questions.mjs\`).
- **Grounded:** every number in the answer appears in a tool output, the question or the system prompt. Clock times, dates, years and site codes are excluded. This is strict: a correct rounding the check does not anticipate counts as unsupported, so flagged numbers were reviewed by hand (below).
- **Baseline:** the same questions sent with no tools, so the model must answer from its own knowledge.
- Each question is asked in a fresh conversation. Free-tier Gemini API; "today" is fixed to the snapshot time.

## Overall
| Run | Correct | Grounded | Model calls / question | Seconds / question | Tokens in / out |
|---|---|---|---|---|---|
`;
for (const r of use) {
  const rs = r.results;
  md += `| ${name(r)} | ${frac(rs, (x) => x.pass)} | ${frac(rs, grounded)} | ${mean(rs, (x) => x.model_calls).toFixed(1)} | ${mean(rs, (x) => x.seconds).toFixed(1)} | ${Math.round(mean(rs, (x) => x.tokens.prompt || 0))} / ${Math.round(mean(rs, (x) => x.tokens.output || 0))} |\n`;
}

md += `\n## Correct answers by category\n| Category | ${use.map(name).join(" | ")} |\n|---|${use.map(() => "---").join("|")}|\n`;
for (const c of CATS) {
  md += `| ${CAT_LABEL[c]} | ${use.map((r) => { const rs = r.results.filter((x) => x.category === c); return `${rs.filter((x) => x.pass).length}/${rs.length}`; }).join(" | ")} |\n`;
}

md += `\n## Every question\n| Id | Question | ${use.map(name).join(" | ")} |\n|---|---|${use.map(() => "---").join("|")}|\n`;
for (const q of use[0].results) {
  md += `| ${q.id} | ${q.question.replace(/\|/g, "/")} | ${use.map((r) => { const x = r.results.find((y) => y.id === q.id); if (!x) return "–"; return (x.pass ? "✅" : "❌") + (x.unsupported_numbers?.length ? ` ⚠️ ${x.unsupported_numbers.join(", ")}` : ""); }).join(" | ")} |\n`;
}
md += "\n✅ correct · ❌ incorrect · ⚠️ numbers not found in any tool output (possible invention)\n";

const main = use.find((r) => r.mode === "tools");
if (main) {
  const fails = main.results.filter((x) => !x.pass);
  md += `\n## Failures with tools (${main.model})\n`;
  md += fails.length ? fails.map((x) => `- **${x.id}** ${x.question}\n  - Expected: ${x.note}\n  - Answer: ${x.error ? `error: ${x.error}` : x.answer.replace(/\s+/g, " ").slice(0, 400)}\n  - Tools used: ${x.tools.map((t) => t.tool).join(", ") || "none"}`).join("\n") + "\n" : "None.\n";
  const flagged = main.results.filter((x) => x.unsupported_numbers?.length);
  md += `\n## Unsupported numbers to review by hand (${main.model}, with tools)\n`;
  md += flagged.length ? flagged.map((x) => `- **${x.id}** numbers ${x.unsupported_numbers.join(", ")}: "${x.answer.replace(/\s+/g, " ").slice(0, 300)}"\n  - Review verdict: _to fill in (rounding / derived / invented)_`).join("\n") + "\n" : "None: every number in every answer traced back to a tool output.\n";
  const tools = {};
  for (const x of main.results) for (const t of x.tools) tools[t.tool] = (tools[t.tool] || 0) + 1;
  md += `\n## Tool use (${main.model})\n| Tool | Calls |\n|---|---|\n${Object.entries(tools).sort((a, b) => b[1] - a[1]).map(([t, c]) => `| \`${t}\` | ${c} |`).join("\n")}\n`;
}

md += `
## Threats to validity
1. **Automatic checks are keyword and number based.** A correct answer phrased unexpectedly can fail, and a wrong answer can pass by containing the right number in another context. Every failure above was read by hand.
2. **${n} questions is a small sample**, written by the developer; they may not reflect what the public actually asks.
3. **One run per question.** LLM output varies between runs; repeating the suite would give a spread rather than a single figure.
4. **Free-tier model.** Larger Gemini models may score differently; the harness accepts \`--model\` to compare.
5. **Snapshot-specific.** Answers depend on that day's data (e.g. whether anything was spilling near a place).
`;

fs.writeFileSync(OUT, md);
console.log(`Wrote ${path.relative(ROOT, OUT)} from ${use.length} run(s) on ${snapshot}`);
